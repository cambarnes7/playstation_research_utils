/*
 * MP4 payload injection and command interface for PS5 FW 4.03.
 *
 * Ported from fail0verflow's prosperous exploit.
 *
 * This module handles:
 *   1. Injecting the AArch64 EL3 payload into MP4 DRAM
 *   2. Hooking mDbg_intr to redirect to our payload
 *   3. Providing a command interface to communicate with the payload
 *
 * The injection works by:
 *   - Writing a thunk at 0x600E0000 (within MP4 DRAM)
 *   - Writing the main payload at 0x607F1000
 *   - Patching the BL mDbg_intr instruction at 0x109854 to branch
 *     to our thunk instead
 *   - Enabling QAF flag in mm4p_flags so the payload is activated
 *
 * After injection, the x86 host communicates with the A53 payload
 * via c2p (CPU-to-Processor) mailbox registers accessible through
 * BAR2 MMIO at physical address 0xE0400000.
 */

